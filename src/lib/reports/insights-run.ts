import "server-only";
import type { Actor } from "@/lib/auth/actor";
import { serverNow } from "@/lib/data";
import { deriveFindings, INSIGHTS_VERSION, type Finding } from "./insights";
import { resolveQuarter, rpcRows, type GovernanceItem, type QuarterRow, type WeeklyRow } from "./run";

export interface InsightsResult {
  generatedAt: string; generatedBy: string; model: null; periodLabel: string; scope: string; findings: Finding[];
  disclosure: string; quarterId: string | null;
}

export async function runInsights(actor: Actor, quarterId?: string): Promise<InsightsResult> {
  const orgWide = actor.permissions.has("weekly_report.view_all");
  const q = await resolveQuarter(quarterId);
  const generatedAt = await serverNow();
  const disclosure = "Generated by a rules engine from the same authoritative data as the reports. No AI model was used and no data left the application. Findings state measured evidence only and never assert a cause.";
  if (!q) return { generatedAt, generatedBy: INSIGHTS_VERSION, model: null, periodLabel: "No quarter", scope: "", findings: [], disclosure, quarterId: null };
  const [weekly, quarter, governance] = await Promise.all([
    rpcRows<WeeklyRow>("read_report_weekly_scores", { p_quarter_id: q.id, p_bu: null }),
    rpcRows<QuarterRow>("read_report_quarter_scores", { p_quarter_id: q.id }),
    rpcRows<GovernanceItem>("read_report_governance_items", {}),
  ]);
  const findings = deriveFindings({
    period: `Q${q.quarter_number} ${q.year}`, orgWide,
    weekly: weekly.map((w) => ({ ...w, final_score: w.final_score === null ? null : Number(w.final_score) })),
    quarter: quarter.map((r) => ({ business_unit: r.business_unit, score: r.score === null ? null : Number(r.score), previous_score: r.previous_score === null ? null : Number(r.previous_score), denominator_count: r.denominator_count })),
    governance,
  });
  return { generatedAt, generatedBy: INSIGHTS_VERSION, model: null, periodLabel: `Q${q.quarter_number} ${q.year}`, scope: orgWide ? "All Business Units" : `Business Unit: ${actor.buName ?? "your unit"}`, findings, disclosure, quarterId: q.id };
}
