"use client";

import { OutcomeCorrectionButtons } from "../../session-correction-actions";
import Link from "next/link";
import { useMemo, useState } from "react";
import { ApiFailure, apiRequest, Modal, useAction } from "@/components/ui/client";
import { Badge, Banner, Button, Card, CardHeader, EmptyState, Input, Label, PageHeader, Select, Textarea, Field, DataTable } from "@/components/ui/primitives";
import { wat } from "@/components/status";
import { EvidenceUploadButton } from "@/components/ui/evidence-upload";
import type { RosterView } from "@/lib/data/governance";
import { formatWeekLabel } from "@/lib/domain/week-label";

// Statuses HR can choose by hand. VIRTUAL_PRESENT is system-generated by Skip OKR only.
const MANUAL = [
  ["PRESENT", "Present"], ["ABSENT", "Absent"], ["ON_LEAVE", "On leave"], ["EXCUSED", "Excused"], ["ILL", "Ill"],
] as const;
const LABEL: Record<string, string> = { PRESENT: "Present", ABSENT: "Absent", ON_LEAVE: "On leave", EXCUSED: "Excused", ILL: "Ill", VIRTUAL_PRESENT: "Virtual present" };

export function StatusPill({ status }: { status: string }) {
  if (status === "VIRTUAL_PRESENT") {
    return <Badge tone="warn" title="OKR session skipped this week; not a physical-attendance assertion">⚠ Virtual present · skipped week</Badge>;
  }
  const tone = status === "PRESENT" ? "done" : status === "ABSENT" ? "critical" : "info";
  return <Badge tone={tone}>{LABEL[status] ?? status}</Badge>;
}

export function RosterWorkspace({ roster, caps }: { roster: RosterView; caps: { manage: boolean; request: boolean; correct: boolean; emergency: boolean } }) {
  const { session, week, rows, tally } = roster;
  const { run, pending } = useAction();
  const [correct, setCorrect] = useState<RosterView["rows"][number] | null>(null);
  const [skipOpen, setSkipOpen] = useState(false);
  const [finOpen, setFinOpen] = useState(false);
  const [filter, setFilter] = useState("");
  const skipped = session.outcome === "SKIPPED";
  const draft = session.roster_status === "DRAFT" && caps.manage;
  const finalised = session.roster_status === "FINALIZED";
  const holiday = week.reporting_state === "ORGANIZATION_HOLIDAY";
  const shown = useMemo(() => rows.filter((r) => !filter || r.name.toLowerCase().includes(filter.toLowerCase()) || r.business_unit.toLowerCase().includes(filter.toLowerCase())), [rows, filter]);
  const exceptions = rows.filter((r) => r.effective_status !== "PRESENT" && r.effective_status !== "VIRTUAL_PRESENT").length;

  return (
    <>
      <PageHeader title={`OKR session · ${formatWeekLabel(week)}`} description={`Session date ${session.session_date}. Attendance never changes the weekly report locks.`}
        actions={<>
          {session.outcome === "HELD" || session.outcome === "SKIPPED" ? <OutcomeCorrectionButtons sessionId={session.id} outcome={session.outcome} canRequest={caps.correct} canEmergency={caps.emergency} /> : null}
          <Link href="/governance" className="rounded-lg border border-line bg-panel px-4 py-2 text-sm">All sessions</Link>
        </>} />
      <div className="space-y-6">
        {skipped ? (
          <Banner tone="warn" title="SKIPPED WEEK · VIRTUAL PRESENT">
            The physical OKR session was skipped{session.outcome_by_name ? ` by ${session.outcome_by_name}` : ""}{session.outcome_at ? ` on ${wat(session.outcome_at)}` : ""}.
            {session.skip_reason ? <> Reason: <strong>{session.skip_reason}</strong>.</> : null}
            {" "}{session.staff_count} staff were tagged VIRTUAL PRESENT. No one needs marking individually and no absence violation is generated.
            Every BU must still submit its weekly report with a manually written performance summary, and the report is reviewed as usual.
          </Banner>
        ) : null}
        {session.outcome === "HELD" ? <Banner tone="locked" title="Attendance saved — original roster is immutable.">To correct an error, submit an attendance amendment request. It changes the effective status only after an independent approval.</Banner> : null}
        {holiday ? <Banner tone="info" title="ORGANIZATION HOLIDAY · REPORT NOT REQUIRED">This reporting week is a holiday; there is no OKR session to run or skip.</Banner> : null}

        {session.roster_status === "NONE" && !skipped ? (
          <Card>
            <EmptyState title="No roster yet" action={caps.manage ? (
              <div className="flex flex-wrap justify-center gap-2">
                <Button disabled={pending} onClick={() => run(() => apiRequest("POST", `governance-sessions/${session.id}/attendance`), { success: "Roster created: every active staff member is Present." })}>Create roster (everyone Present)</Button>
              </div>) : undefined}>
              Creating the roster pre-populates every active staff member as <strong>Present</strong>. After the session you only change the exceptions.
              If the physical session will not take place, use <em>Skip OKR for this week</em> instead.
            </EmptyState>
          </Card>
        ) : (
          <Card>
            <CardHeader title="Roster" description={finalised ? (skipped ? "Generated by Skip OKR. Read-only." : "Finalised. Read-only source record.") : "Draft: change only the exceptions, then finalise."}
              action={<div className="flex flex-wrap items-center gap-2">{Object.entries(tally).map(([k, n]) => <span key={k} className="inline-flex items-center gap-1 text-sm"><StatusPill status={k} /><strong className="tabular-nums">{n}</strong></span>)}</div>} />
            <div className="space-y-4 px-6 py-4">
              {draft ? <p className="text-sm text-muted" role="status">{exceptions === 0 ? "Everyone is Present." : `${exceptions} exception${exceptions === 1 ? "" : "s"} marked.`} Changes save as you make them; nothing is final until you finalise.</p> : null}
              <Field id="roster-filter" label="Filter staff"><Input className="max-w-xs" value={filter} onChange={(e) => setFilter(e.target.value)} placeholder="Name or BU" /></Field>
              <DataTable caption="Attendance roster" columns={[{ label: "Staff" }, { label: "BU" }, { label: finalised ? "Effective status" : "Status" }, { label: "Actions", srOnly: true }]}>
                    {shown.map((r) => (
                      <tr key={r.id} className="border-b border-line last:border-0">
                        <td><p className="font-medium">{r.name}</p><p className="text-xs text-muted">{r.email}</p></td>
                        <td>{r.business_unit}</td>
                        <td>
                          {draft ? (
                            <>
                              <label className="sr-only" htmlFor={`st-${r.id}`}>Status for {r.name}</label>
                              <Select id={`st-${r.id}`} className="max-w-44" value={r.source_status} disabled={pending}
                                onChange={(e) => run(() => apiRequest("PATCH", `attendance-records/${r.id}`, { status: e.target.value, notes: r.notes }))}>
                                {MANUAL.map(([v, l]) => <option key={v} value={v}>{l}</option>)}
                              </Select>
                            </>
                          ) : (
                            <span className="inline-flex flex-wrap items-center gap-2"><StatusPill status={r.effective_status} />
                              {r.effective_status !== r.source_status ? <span className="text-xs text-muted">amended from {LABEL[r.source_status] ?? r.source_status}</span> : null}
                              {r.pending_request_id ? <Badge tone="warn">Amendment pending</Badge> : null}</span>
                          )}
                        </td>
                        <td className="text-right">
                          {finalised && !skipped && caps.request && !r.pending_request_id ? <Button size="sm" variant="ghost" onClick={() => setCorrect(r)}>Request correction</Button> : null}
                        </td>
                      </tr>
                    ))}
                  </DataTable>
            </div>
          </Card>
        )}

        {caps.manage && !skipped && !finalised && !holiday ? (
          <Card>
            <div className="flex flex-wrap items-center justify-between gap-4 px-6 py-4">
              <div className="text-sm"><p className="font-medium">After the session</p><p className="text-muted">Finalising makes the source roster immutable.</p></div>
              <div className="flex flex-wrap gap-2">
                {session.roster_status === "DRAFT" ? <Button disabled={pending} onClick={() => setFinOpen(true)}>Review &amp; finalise roster</Button> : null}
                <Button variant="secondary" disabled={pending} onClick={() => setSkipOpen(true)}>Skip OKR for this week</Button>
              </div>
            </div>
          </Card>
        ) : null}
      </div>

      <Modal open={finOpen} onOpenChange={setFinOpen} title="Finalise the attendance roster?" description="After you confirm, the source attendance becomes immutable. Later errors can only be corrected through an independently approved amendment request.">
        <ul className="mb-4 space-y-1 text-sm">{Object.entries(tally).map(([k, n]) => <li key={k} className="flex items-center justify-between"><StatusPill status={k} /><strong className="tabular-nums">{n}</strong></li>)}</ul>
        <div className="flex justify-end gap-2"><Button variant="secondary" onClick={() => setFinOpen(false)}>Back to roster</Button>
          <Button disabled={pending} onClick={async () => { const ok = await run(() => apiRequest("POST", `governance-sessions/${session.id}/attendance/finalize`, { confirm: true }), { success: "Attendance saved — original roster is immutable." }); if (ok) setFinOpen(false); }}>Confirm and finalise</Button></div>
      </Modal>

      <SkipDialog open={skipOpen} onOpenChange={setSkipOpen} sessionId={session.id} count={rows.length} />
      {correct ? <CorrectionDialog row={correct} onClose={() => setCorrect(null)} /> : null}
    </>
  );
}

function SkipDialog({ open, onOpenChange, sessionId, count }: { open: boolean; onOpenChange: (o: boolean) => void; sessionId: string; count: number }) {
  const { run, pending } = useAction();
  const [reason, setReason] = useState("");
  const [key] = useState(() => crypto.randomUUID()); // one key per dialog instance => a double click cannot skip twice
  return (
    <Modal open={open} onOpenChange={onOpenChange} title="Skip OKR for this week?"
      description="This will mark the physical session as SKIPPED and tag every staff member VIRTUAL PRESENT. No one needs to be marked individually. Every BU must still submit its weekly report, manually enter a performance summary for this week, and complete normal review.">
      <p className="mb-4 text-sm text-muted">{count > 0 ? `${count} staff are currently on the roster.` : "Every active staff member will be tagged."} All BU Leads will be notified immediately, with your reason. This cannot be quietly undone.</p>
      <Field id="skip-reason" label="Why is the session being skipped?" hint="Required. Every BU Lead will read this."><Textarea value={reason} onChange={(e) => setReason(e.target.value)} maxLength={2000} required /></Field>
      <div className="flex justify-end gap-2">
        <Button variant="secondary" onClick={() => onOpenChange(false)}>Cancel</Button>
        <Button variant="danger" disabled={pending || reason.trim().length < 5} onClick={async () => {
          const ok = await run(async () => {
            const r = await apiRequest<{ staff_tagged: number; notified_bu_leads: number }>("POST", `governance-sessions/${sessionId}/skip-okr`, { confirm: true, idempotencyKey: key, reason: reason.trim() });
            return r;
          }, { success: "OKR session skipped. All BU Leads were notified." });
          if (ok) onOpenChange(false);
        }}>{pending ? "Skipping…" : "Skip OKR for this week"}</Button>
      </div>
    </Modal>
  );
}

function CorrectionDialog({ row, onClose }: { row: RosterView["rows"][number]; onClose: () => void }) {
  const { run, pending } = useAction();
  const [proposed, setProposed] = useState("");
  const [reason, setReason] = useState("");
  const [evidence, setEvidence] = useState("");
  const [key] = useState(() => crypto.randomUUID());
  const [err, setErr] = useState<string | null>(null);
  return (
    <Modal open onOpenChange={(o) => !o && onClose()} title="Request attendance correction"
      description="The effective status will not change until an independent approver decides. The original roster value is never overwritten.">
      <form className="space-y-3" onSubmit={async (e) => {
        e.preventDefault(); setErr(null);
        const ok = await run(async () => {
          try {
            return await apiRequest("POST", `attendance-records/${row.id}/amendment-requests`, { proposedStatus: proposed, reason, evidenceRefs: evidence.trim() ? [{ ref: evidence.trim() }] : [], idempotencyKey: key });
          } catch (x) { setErr((x as ApiFailure).message); throw x; }
        }, { success: "Correction requested. Awaiting independent approval." });
        if (ok) onClose();
      }}>
        <p className="text-sm"><strong>{row.name}</strong> · original <StatusPill status={row.source_status} /> · effective <StatusPill status={row.effective_status} /></p>
        <div><Label htmlFor="am-status">Proposed status</Label>
          <Select id="am-status" value={proposed} onChange={(e) => setProposed(e.target.value)} required><option value="">Select…</option>{MANUAL.filter(([v]) => v !== row.effective_status).map(([v, l]) => <option key={v} value={v}>{l}</option>)}</Select></div>
        <Field id="am-reason" label="Reason (required)"><Textarea value={reason} onChange={(e) => setReason(e.target.value)} maxLength={2000} required /></Field>
        <Field id="am-ev" label="Supporting evidence reference (optional)"><Input value={evidence} onChange={(e) => setEvidence(e.target.value)} maxLength={500} placeholder="e.g. document or ticket reference" /></Field>
        <EvidenceUploadButton entityType="SESSION" entityId={row.id} label="Attach supporting evidence" />
        {err ? <p role="alert" className="text-sm text-[var(--critical-fg)]">{err}</p> : null}
        <div className="flex justify-end gap-2"><Button variant="secondary" onClick={onClose}>Cancel</Button><Button type="submit" disabled={pending || !proposed || !reason.trim()}>Submit request</Button></div>
      </form>
    </Modal>
  );
}
