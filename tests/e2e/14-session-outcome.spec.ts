import { expect, test } from "@playwright/test";
import { formatWeekLabel } from "../../src/lib/domain/week-label";
import { answerStepUpIfAsked, expectNoA11yViolations, loginAs, query } from "./helpers";

/**
 * Skip OKR for this week, and putting it right when it was a mistake. Closes AC-OP-4 (the skipped-week screen was never exercised in a
 * browser) and exercises the session-outcome correction: HR asks, an Admin approves, a different person executes; a Super Admin can do it
 * in one step in an emergency.
 */
let label = "";
let sessionPath = "";

test.beforeAll(async () => {
  const w = (await query<{ id: string; week_number: number; week_start_at: Date }>(
    `select w.id, w.week_number, w.week_start_at from reporting_weeks w join quarters q on q.id = w.quarter_id
      where q.status = 'ACTIVE' and w.reporting_state = 'NORMAL' and w.status in ('OPEN','FINAL_LOCKED')
        and not exists (select 1 from governance_sessions s where s.reporting_week_id = w.id) order by w.week_start_at desc limit 1`))[0];
  if (!w) throw new Error("no week without a session: run the earlier specs first");
  label = formatWeekLabel({ week_number: w.week_number, week_start_at: w.week_start_at });
});

const row = (page: import("@playwright/test").Page) => page.getByRole("listitem").filter({ hasText: label }).first();

test.describe.serial("session outcome", () => {
  test("HR skips the week; the screen says so, offers no editing, and the whole roster is virtually present", async ({ page }) => {
    await loginAs(page, "hr@4core.local");
    await page.goto("/governance");
    await row(page).getByRole("button", { name: "Create session" }).click();
    await expect(page.getByRole("heading", { level: 1 })).toContainText(label);      // creating the session opens it
    sessionPath = new URL(page.url()).pathname;
    await page.getByRole("button", { name: "Skip OKR for this week" }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Skip OKR for this week" }).click();
    await expect(page.getByText("OKR session skipped. All BU Leads were notified.")).toBeVisible();

    await expect(page.getByText("SKIPPED WEEK · VIRTUAL PRESENT").first()).toBeVisible();
    await expect(page.getByText(/staff were tagged VIRTUAL PRESENT/)).toBeVisible();
    await expect(page.getByText("Generated by Skip OKR. Read-only.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Finalise roster" })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Request correction" })).toHaveCount(0);        // skip rows cannot be amended one by one
    await expect(page.locator("select")).toHaveCount(0);                                         // no status can be changed
    const sessionId = sessionPath.split("/").pop()!;
    const rows = await query<{ status: string; source: string }>("select distinct status, source from attendance_records where governance_session_id = $1", [sessionId]);
    expect(rows).toEqual([{ status: "VIRTUAL_PRESENT", source: "SKIP" }]);
    await expectNoA11yViolations(page, "skipped session");
  });

  test("a mistaken skip is put right in three steps by three different people, and the old roster is archived", async ({ page }) => {
    const sessionId = sessionPath.split("/").pop()!;
    const staff = (await query<{ n: number }>("select count(*)::int n from attendance_records where governance_session_id = $1", [sessionId]))[0].n;

    await loginAs(page, "hr@4core.local");
    await page.goto(sessionPath);
    await page.getByRole("button", { name: "Request outcome correction" }).click();
    await page.getByRole("dialog").getByLabel("Reason (required)").fill("The skip was entered on the wrong week");
    await page.getByRole("dialog").getByRole("button", { name: "Send request" }).click();
    await answerStepUpIfAsked(page, "hr@4core.local");
    await expect(page.getByText("Correction requested. A different person must approve it.")).toBeVisible();
    expect((await query<{ outcome: string }>("select outcome from governance_sessions where id = $1", [sessionId]))[0].outcome).toBe("SKIPPED");   // asking changes nothing

    await loginAs(page, "admin@4core.local");
    await page.goto("/governance");
    const queue = page.getByRole("list", { name: "Session outcome corrections" }).getByRole("listitem").filter({ hasText: label }).first();
    await expect(queue).toContainText("Waiting for approval");
    await queue.getByRole("button", { name: /^Approve/ }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Approve", exact: true }).click();
    await answerStepUpIfAsked(page, "admin@4core.local");
    await expect(page.getByText("Approved. It now waits to be executed.")).toBeVisible();

    await loginAs(page, "superadmin@4core.local");
    await page.goto("/governance");
    const q2 = page.getByRole("list", { name: "Session outcome corrections" }).getByRole("listitem").filter({ hasText: label }).first();
    await q2.getByRole("button", { name: /^Reopen the session/ }).click();
    await answerStepUpIfAsked(page, "superadmin@4core.local");
    await expect(page.getByText("Session reopened. The earlier roster is archived.")).toBeVisible();
    await expect(q2).toContainText("Session reopened");

    const after = (await query<{ outcome: string; roster_status: string }>("select outcome, roster_status from governance_sessions where id = $1", [sessionId]))[0];
    expect(after).toEqual({ outcome: "SCHEDULED", roster_status: "NONE" });
    expect((await query<{ n: number }>("select count(*)::int n from attendance_record_archive where governance_session_id = $1", [sessionId]))[0].n).toBe(staff);
    await page.goto(sessionPath);
    await expect(page.getByText("No roster yet")).toBeVisible();
    await expect(page.getByText("SKIPPED WEEK · VIRTUAL PRESENT")).toHaveCount(0);
    await expectNoA11yViolations(page, "reopened session");
  });

  test("a Super Admin can reopen in one step in an emergency, and everyone who runs sessions is alerted", async ({ page }) => {
    const sessionId = sessionPath.split("/").pop()!;
    await loginAs(page, "hr@4core.local");
    await page.goto(sessionPath);
    await page.getByRole("button", { name: "Skip OKR for this week" }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Skip OKR for this week" }).click();
    await expect(page.getByText("OKR session skipped. All BU Leads were notified.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Emergency outcome correction" })).toHaveCount(0);       // HR does not have it

    await loginAs(page, "superadmin@4core.local");
    await page.goto(sessionPath);
    await page.getByRole("button", { name: "Emergency outcome correction" }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByLabel(/Reason \(required, at least 10 characters\)/).fill("short");
    await expect(dialog.getByRole("button", { name: "Reopen the session now" })).toBeDisabled();
    await dialog.getByLabel(/Reason \(required, at least 10 characters\)/).fill("Skipped by mistake during the audit rehearsal");
    await dialog.getByRole("button", { name: "Reopen the session now" }).click();
    await answerStepUpIfAsked(page, "superadmin@4core.local");
    await expect(page.getByText("Session reopened. HR and approvers were alerted.")).toBeVisible();
    expect((await query<{ outcome: string }>("select outcome from governance_sessions where id = $1", [sessionId]))[0].outcome).toBe("SCHEDULED");
    const alerts = await query<{ n: number }>("select count(*)::int n from notifications n join users u on u.id = n.user_id where n.event_type = 'SESSION_CORRECTION_EMERGENCY' and u.email = 'hr@4core.local'");
    expect(alerts[0].n).toBeGreaterThanOrEqual(1);
  });
});
