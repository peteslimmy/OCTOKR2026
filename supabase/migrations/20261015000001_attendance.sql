-- ---------------------------------------------------------------- operations
create or replace function create_governance_session(p_actor uuid, p_week_id uuid) returns uuid
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_w reporting_weeks; v_id uuid; v_date date;
begin
  perform require_permission(p_actor, 'attendance.session.manage');
  select * into v_w from reporting_weeks where id = p_week_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  select id into v_id from governance_sessions where reporting_week_id = p_week_id;
  if v_id is not null then return v_id; end if;
  -- The Tuesday OKR session presents the week that final-locks that same Tuesday (assumption, implementation notes).
  v_date := (v_w.final_lock_at at time zone 'Africa/Lagos')::date;
  insert into governance_sessions (reporting_week_id, session_date) values (p_week_id, v_date) returning id into v_id;
  perform write_audit(p_actor, 'GOVERNANCE_SESSION_CREATED', 'governance_session', v_id::text, null, jsonb_build_object('reporting_week_id', p_week_id, 'session_date', v_date));
  return v_id;
end $$;

create or replace function create_attendance_roster(p_actor uuid, p_session_id uuid) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare s governance_sessions; n int;
begin
  perform require_permission(p_actor, 'attendance.session.manage');
  select * into s from governance_sessions where id = p_session_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if s.outcome = 'SKIPPED' then raise exception 'ATTENDANCE_SESSION_SKIPPED'; end if;
  if s.roster_status <> 'NONE' then return jsonb_build_object('created', false, 'roster_status', s.roster_status, 'staff_count', s.roster_staff_count); end if;
  -- Server-side snapshot of active staff; every row defaults to PRESENT (never a client default).
  insert into attendance_records (governance_session_id, employee_id, business_unit_id, status)
    select p_session_id, e.id, e.business_unit_id, 'PRESENT' from employees e where e.employment_status = 'ACTIVE';
  get diagnostics n = row_count;
  update governance_sessions set roster_status = 'DRAFT', roster_created_at = app_now(), roster_created_by = p_actor, roster_staff_count = n, updated_at = app_now()
   where id = p_session_id;
  perform write_audit(p_actor, 'ATTENDANCE_ROSTER_CREATED', 'governance_session', p_session_id::text, null,
    jsonb_build_object('staff_count', n, 'default_status', 'PRESENT', 'rule', 'all active staff pre-populated as PRESENT'));
  return jsonb_build_object('created', true, 'roster_status', 'DRAFT', 'staff_count', n);
end $$;

create or replace function set_attendance_status(p_actor uuid, p_record_id uuid, p_status text, p_notes text) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare rec attendance_records; s governance_sessions; st attendance_statuses;
begin
  perform require_permission(p_actor, 'attendance.session.manage');
  select * into rec from attendance_records where id = p_record_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  select * into s from governance_sessions where id = rec.governance_session_id;
  if s.outcome = 'SKIPPED' or s.roster_status = 'FINALIZED' then raise exception 'IMMUTABLE_RECORD' using detail = 'finalised attendance cannot be edited; request an amendment'; end if;
  select * into st from attendance_statuses where code = p_status and active;
  if not found or st.system_only then raise exception 'VALIDATION_ERROR' using detail = 'status not selectable'; end if;
  update attendance_records set status = p_status, notes = nullif(btrim(p_notes), ''), updated_at = app_now() where id = p_record_id;
end $$;

create or replace function finalize_attendance_roster(p_actor uuid, p_session_id uuid, p_confirm boolean) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare s governance_sessions; v_counts jsonb;
begin
  perform require_permission(p_actor, 'attendance.session.manage');
  if p_confirm is not true then raise exception 'VALIDATION_ERROR' using detail = 'confirmation required: finalisation makes the roster immutable'; end if;
  select * into s from governance_sessions where id = p_session_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if s.roster_status = 'FINALIZED' then raise exception 'INVALID_STATE_TRANSITION' using detail = 'already finalised'; end if;
  if s.roster_status <> 'DRAFT' then raise exception 'INVALID_STATE_TRANSITION' using detail = 'no roster has been created'; end if;
  select coalesce(jsonb_object_agg(status, n), '{}'::jsonb) into v_counts
    from (select status, count(*) n from attendance_records where governance_session_id = p_session_id group by status) t;
  update governance_sessions set roster_status = 'FINALIZED', outcome = 'HELD', outcome_at = app_now(), outcome_by = p_actor,
         roster_finalised_at = app_now(), roster_finalised_by = p_actor, updated_at = app_now() where id = p_session_id;
  perform write_audit(p_actor, 'ATTENDANCE_ROSTER_FINALISED', 'governance_session', p_session_id::text, jsonb_build_object('roster_status', 'DRAFT'),
    jsonb_build_object('roster_status', 'FINALIZED', 'outcome', 'HELD', 'counts', v_counts));
  return jsonb_build_object('counts', v_counts);
end $$;

-- Skip OKR for this week: atomic, idempotent, all-or-nothing (FR-ATT-006/009).
create or replace function skip_okr_session(p_actor uuid, p_session_id uuid, p_confirm boolean, p_idempotency_key text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare s governance_sessions; w reporting_weeks; n int; v_ref uuid := gen_random_uuid(); v_bu_leads uuid[];
begin
  perform require_permission(p_actor, 'attendance.session.manage');
  if p_confirm is not true then raise exception 'VALIDATION_ERROR' using detail = 'explicit confirmation required'; end if;
  if p_idempotency_key is null or btrim(p_idempotency_key) = '' then raise exception 'VALIDATION_ERROR' using detail = 'idempotency key required'; end if;
  select * into s from governance_sessions where id = p_session_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if s.outcome = 'SKIPPED' then
    if s.skip_idempotency_key = p_idempotency_key then
      return jsonb_build_object('replayed', true, 'outcome', 'SKIPPED', 'staff_tagged', s.staff_tagged_count, 'operation_ref', s.skip_operation_ref);
    end if;
    raise exception 'INVALID_STATE_TRANSITION' using detail = 'session already skipped';
  end if;
  if s.roster_status = 'FINALIZED' then raise exception 'ATTENDANCE_SESSION_NOT_SKIPPABLE' using detail = 'a held roster is already finalised'; end if;
  select * into w from reporting_weeks where id = s.reporting_week_id;
  if w.reporting_state = 'ORGANIZATION_HOLIDAY' then raise exception 'REPORTING_NOT_REQUIRED' using detail = 'an organisation-holiday week has no OKR session to skip'; end if;

  perform set_config('app.attendance_skip', 'on', true);
  delete from attendance_records where governance_session_id = p_session_id;      -- discard any unfinalised draft
  insert into attendance_records (governance_session_id, employee_id, business_unit_id, status, source)
    select p_session_id, e.id, e.business_unit_id, 'VIRTUAL_PRESENT', 'SKIP' from employees e where e.employment_status = 'ACTIVE';
  get diagnostics n = row_count;
  perform set_config('app.attendance_skip', 'off', true);

  update governance_sessions set outcome = 'SKIPPED', outcome_at = app_now(), outcome_by = p_actor, skip_operation_ref = v_ref,
         staff_tagged_count = n, skip_idempotency_key = p_idempotency_key, roster_status = 'FINALIZED', roster_staff_count = n,
         roster_finalised_at = app_now(), roster_finalised_by = p_actor, updated_at = app_now()
   where id = p_session_id;
  perform write_audit(p_actor, 'OKR_SESSION_SKIPPED', 'governance_session', p_session_id::text, jsonb_build_object('outcome', s.outcome),
    jsonb_build_object('outcome', 'SKIPPED', 'staff_tagged_virtual_present', n, 'operation_ref', v_ref, 'reporting_week_id', s.reporting_week_id,
                       'note', 'weekly BU reports and manual summaries remain mandatory'));
  v_bu_leads := users_with_role('BU_LEAD');
  perform notify_users(v_bu_leads, 'OKR_SESSION_SKIPPED', 'reporting_week', s.reporting_week_id::text,
    'OKR session skipped — your weekly report is still required',
    'The physical OKR session was skipped, but weekly reporting remains mandatory. Submit your report and enter the required performance summary for the week.',
    'skip:' || p_session_id);
  return jsonb_build_object('replayed', false, 'outcome', 'SKIPPED', 'staff_tagged', n, 'operation_ref', v_ref, 'notified_bu_leads', cardinality(v_bu_leads));
end $$;

