-- ---------------------------------------------------------------- amendment workflow
create or replace function submit_attendance_amendment(
  p_actor uuid, p_record_id uuid, p_proposed text, p_reason text, p_evidence jsonb, p_idempotency_key text
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare rec attendance_records; s governance_sessions; v_existing attendance_amendment_requests; v_eff text; v_id uuid; st attendance_statuses;
begin
  perform require_permission(p_actor, 'attendance.amendment.request');
  if p_idempotency_key is null or btrim(p_idempotency_key) = '' then raise exception 'VALIDATION_ERROR' using detail = 'idempotency key required'; end if;
  select * into v_existing from attendance_amendment_requests where idempotency_key = p_idempotency_key;
  if found then
    if v_existing.requested_by <> p_actor or v_existing.attendance_record_id <> p_record_id then raise exception 'IDEMPOTENCY_KEY_REUSED'; end if;
    return jsonb_build_object('request_id', v_existing.id, 'replayed', true, 'status', v_existing.status);
  end if;
  if p_reason is null or btrim(p_reason) = '' then raise exception 'ATTENDANCE_AMENDMENT_REASON_REQUIRED'; end if;
  select * into rec from attendance_records where id = p_record_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  select * into s from governance_sessions where id = rec.governance_session_id;
  if s.outcome <> 'HELD' or s.roster_status <> 'FINALIZED' then raise exception 'ATTENDANCE_SESSION_NOT_AMENDABLE'; end if;   -- skipped rows are never individually amendable
  select * into st from attendance_statuses where code = p_proposed and active;
  if not found or st.system_only then raise exception 'VALIDATION_ERROR' using detail = 'proposed status not allowed'; end if;
  v_eff := attendance_effective_status(p_record_id);
  if v_eff = p_proposed then raise exception 'VALIDATION_ERROR' using detail = 'proposed status equals the current effective status'; end if;
  if jsonb_typeof(coalesce(p_evidence, '[]'::jsonb)) <> 'array' then raise exception 'VALIDATION_ERROR' using detail = 'evidence must be a list of references'; end if;
  begin
    insert into attendance_amendment_requests (attendance_record_id, source_status_snapshot, effective_status_snapshot, proposed_status, reason, evidence_refs, requested_by, idempotency_key)
      values (p_record_id, rec.status, v_eff, p_proposed, btrim(p_reason), coalesce(p_evidence, '[]'::jsonb), p_actor, p_idempotency_key) returning id into v_id;
  exception when unique_violation then raise exception 'ATTENDANCE_AMENDMENT_ALREADY_PENDING'; end;
  insert into attendance_amendment_events (request_id, event_type, actor_user_id, source_status, effective_status, proposed_status, reason)
    values (v_id, 'SUBMITTED', p_actor, rec.status, v_eff, p_proposed, btrim(p_reason));
  perform write_audit(p_actor, 'ATTENDANCE_AMENDMENT_SUBMITTED', 'attendance_amendment_request', v_id::text,
    jsonb_build_object('source', rec.status, 'effective', v_eff), jsonb_build_object('proposed', p_proposed, 'evidence', coalesce(p_evidence, '[]'::jsonb)), btrim(p_reason));
  perform notify_users(array(select u from unnest(users_with_permission('attendance.amendment.approve')) u where u <> p_actor), 'ATTENDANCE_AMENDMENT_SUBMITTED',
    'attendance_amendment_request', v_id::text, 'Attendance amendment awaiting decision', 'A correction to a finalised attendance record needs an independent decision.', 'aar-sub:' || v_id);
  return jsonb_build_object('request_id', v_id, 'replayed', false, 'status', 'PENDING');
end $$;

create or replace function decide_attendance_amendment(
  p_actor uuid, p_request_id uuid, p_approve boolean, p_reason text, p_idempotency_key text
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare r attendance_amendment_requests; v_eff text; rec attendance_records;
begin
  perform require_permission(p_actor, 'attendance.amendment.approve');
  if p_idempotency_key is null or btrim(p_idempotency_key) = '' then raise exception 'VALIDATION_ERROR' using detail = 'idempotency key required'; end if;
  select * into r from attendance_amendment_requests where id = p_request_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if r.decision_key = p_idempotency_key then return jsonb_build_object('request_id', r.id, 'status', r.status, 'replayed', true); end if;
  if r.requested_by = p_actor then raise exception 'ATTENDANCE_AMENDMENT_SELF_APPROVAL'; end if;   -- identity resolved server-side, never from the client
  if r.status <> 'PENDING' then raise exception 'INVALID_STATE_TRANSITION' using detail = 'request is already ' || r.status; end if;
  select * into rec from attendance_records where id = r.attendance_record_id for update;
  v_eff := attendance_effective_status(r.attendance_record_id);

  if p_approve and v_eff <> r.effective_status_snapshot then
    -- stale: persist the rejection so it stays auditable, then the API reports a conflict
    update attendance_amendment_requests set status = 'REJECTED', decided_by = p_actor, decided_at = app_now(),
           decision_reason = 'STALE: effective status changed from ' || r.effective_status_snapshot || ' to ' || v_eff, decision_key = p_idempotency_key where id = r.id;
    insert into attendance_amendment_events (request_id, event_type, actor_user_id, source_status, effective_status, proposed_status, reason)
      values (r.id, 'STALE_REJECTED', p_actor, rec.status, v_eff, r.proposed_status, 'stale snapshot');
    perform write_audit(p_actor, 'ATTENDANCE_AMENDMENT_STALE', 'attendance_amendment_request', r.id::text, null, jsonb_build_object('snapshot', r.effective_status_snapshot, 'current', v_eff), null, null, 'DENIED');
    perform notify_users(array[r.requested_by], 'ATTENDANCE_AMENDMENT_REJECTED', 'attendance_amendment_request', r.id::text, 'Attendance amendment could not be applied',
      'The record changed after you submitted the request. Submit a new request against the current status.', 'aar-dec:' || r.id);
    return jsonb_build_object('request_id', r.id, 'status', 'STALE_REJECTED', 'replayed', false);
  end if;

  update attendance_amendment_requests set status = case when p_approve then 'APPROVED' else 'REJECTED' end, decided_by = p_actor, decided_at = app_now(),
         decision_reason = nullif(btrim(p_reason), ''), decision_key = p_idempotency_key where id = r.id;
  insert into attendance_amendment_events (request_id, event_type, actor_user_id, source_status, effective_status, proposed_status, reason)
    values (r.id, case when p_approve then 'APPROVED' else 'REJECTED' end, p_actor, rec.status, v_eff, r.proposed_status, nullif(btrim(p_reason), ''));
  perform write_audit(p_actor, case when p_approve then 'ATTENDANCE_AMENDMENT_APPROVED' else 'ATTENDANCE_AMENDMENT_REJECTED' end, 'attendance_amendment_request', r.id::text,
    jsonb_build_object('effective', v_eff), jsonb_build_object('resulting_effective', case when p_approve then r.proposed_status else v_eff end), nullif(btrim(p_reason), ''));
  perform notify_users(array[r.requested_by], case when p_approve then 'ATTENDANCE_AMENDMENT_APPROVED' else 'ATTENDANCE_AMENDMENT_REJECTED' end,
    'attendance_amendment_request', r.id::text,
    case when p_approve then 'Attendance amendment approved' else 'Attendance amendment rejected' end,
    case when p_approve then 'Your attendance correction was approved; the effective status has been updated.'
         else 'Your attendance correction was rejected.' || coalesce(' Reason: ' || nullif(btrim(p_reason), ''), '') end,
    'aar-dec:' || r.id);
  return jsonb_build_object('request_id', r.id, 'status', case when p_approve then 'APPROVED' else 'REJECTED' end, 'replayed', false);
end $$;

-- ---------------------------------------------------------------- read model: roster with tallies
create or replace function read_session_roster(p_session_id uuid) returns jsonb
language plpgsql stable security invoker set search_path = public, pg_temp as $$
declare s governance_sessions; w reporting_weeks;
begin
  select * into s from governance_sessions where id = p_session_id;
  if not found then return null; end if;
  select * into w from reporting_weeks where id = s.reporting_week_id;
  return jsonb_build_object(
    'session', jsonb_build_object('id', s.id, 'reporting_week_id', s.reporting_week_id, 'session_date', s.session_date, 'outcome', s.outcome,
      'roster_status', s.roster_status, 'outcome_at', s.outcome_at, 'staff_count', s.roster_staff_count, 'skip_operation_ref', s.skip_operation_ref,
      'outcome_by_name', (select e.first_name || ' ' || e.last_name from users u join employees e on e.id = u.employee_id where u.id = s.outcome_by)),
    'week', jsonb_build_object('week_number', w.week_number, 'week_year', w.week_year, 'week_start_at', w.week_start_at, 'reporting_state', w.reporting_state),
    'rows', coalesce((select jsonb_agg(jsonb_build_object(
        'id', a.id, 'employee_id', a.employee_id, 'name', e.first_name || ' ' || e.last_name, 'email', e.email,
        'business_unit', b.name, 'source_status', a.status, 'effective_status', attendance_effective_status(a.id), 'notes', a.notes, 'source', a.source,
        'pending_request_id', (select r.id from attendance_amendment_requests r where r.attendance_record_id = a.id and r.status = 'PENDING'))
        order by e.last_name, e.first_name)
      from attendance_records a join employees e on e.id = a.employee_id join business_units b on b.id = a.business_unit_id
      where a.governance_session_id = s.id), '[]'::jsonb),
    'tally', coalesce((select jsonb_object_agg(st, n) from (select attendance_effective_status(a.id) st, count(*) n from attendance_records a where a.governance_session_id = s.id group by 1) t), '{}'::jsonb));
end $$;

create or replace function read_amendment_requests(p_status text default null) returns jsonb
language sql stable security invoker set search_path = public, pg_temp as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', r.id, 'status', r.status, 'requested_at', r.requested_at, 'reason', r.reason, 'evidence_refs', r.evidence_refs,
    'source_status', r.source_status_snapshot, 'effective_status', r.effective_status_snapshot, 'proposed_status', r.proposed_status,
    'requested_by', r.requested_by, 'requester_name', (select e.first_name || ' ' || e.last_name from users u join employees e on e.id = u.employee_id where u.id = r.requested_by),
    'decided_at', r.decided_at, 'decision_reason', r.decision_reason,
    'decider_name', (select e.first_name || ' ' || e.last_name from users u join employees e on e.id = u.employee_id where u.id = r.decided_by),
    'employee_name', (select e.first_name || ' ' || e.last_name from attendance_records a join employees e on e.id = a.employee_id where a.id = r.attendance_record_id),
    'session_date', (select s.session_date from attendance_records a join governance_sessions s on s.id = a.governance_session_id where a.id = r.attendance_record_id),
    'events', coalesce((select jsonb_agg(jsonb_build_object('type', ev.event_type, 'at', ev.created_at, 'reason', ev.reason,
        'actor', (select e.first_name || ' ' || e.last_name from users u join employees e on e.id = u.employee_id where u.id = ev.actor_user_id)) order by ev.created_at, ev.id)
        from attendance_amendment_events ev where ev.request_id = r.id), '[]'::jsonb)
  ) order by r.requested_at desc), '[]'::jsonb)
  from attendance_amendment_requests r where (p_status is null or r.status = p_status);
$$;

