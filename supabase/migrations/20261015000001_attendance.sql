  requested_by = auth.uid() or auth_has_any(array['attendance.amendment.view','attendance.amendment.approve']));
create policy read_scoped on attendance_amendment_events for select to authenticated using (
  auth_has_any(array['attendance.amendment.view','attendance.amendment.approve'])
  or exists (select 1 from attendance_amendment_requests r where r.id = request_id and r.requested_by = auth.uid()));
create policy read_all on weekly_quotes for select to authenticated using (true);
create policy read_own on user_permission_grants for select to authenticated using (user_id = auth.uid() or auth_has_permission('roles.manage'));

