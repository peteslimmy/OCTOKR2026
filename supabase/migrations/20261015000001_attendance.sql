-- Finalised and skip-generated source rows are immutable at the database layer (BR-ATT-003, ADR-031).
create or replace function guard_attendance_record() returns trigger
language plpgsql as $$
declare s governance_sessions;
begin
  select * into s from governance_sessions where id = old.governance_session_id;
  if s.roster_status = 'FINALIZED' or s.outcome = 'SKIPPED' then
    if coalesce(current_setting('app.attendance_skip', true), '') = 'on' and tg_op = 'DELETE' and s.roster_status <> 'FINALIZED' then
      return old;
    end if;
    raise exception 'IMMUTABLE_RECORD' using detail = 'finalised attendance cannot be edited or deleted; request an amendment';
  end if;
  if tg_op = 'DELETE' then
    if coalesce(current_setting('app.attendance_skip', true), '') <> 'on' then raise exception 'IMMUTABLE_RECORD' using detail = 'roster rows are not deleted'; end if;
    return old;
  end if;
  if new.governance_session_id <> old.governance_session_id or new.employee_id <> old.employee_id or new.business_unit_id <> old.business_unit_id then
    raise exception 'IMMUTABLE_RECORD';
  end if;
  return new;
end $$;
create trigger attendance_records_guard before update or delete on attendance_records for each row execute function guard_attendance_record();

-- ---------------------------------------------------------------- amendments
create table attendance_amendment_requests (
  id                         uuid primary key default gen_random_uuid(),
  attendance_record_id       uuid not null references attendance_records(id) on delete restrict,
  source_status_snapshot     text not null,
  effective_status_snapshot  text not null,
  proposed_status            text not null references attendance_statuses(code),
  reason                     text not null check (btrim(reason) <> ''),
  evidence_refs              jsonb not null default '[]'::jsonb,
  requested_by               uuid not null references users(id),
  requested_at               timestamptz not null default app_now(),
  status                     text not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED')),
  decided_by                 uuid references users(id),
  decided_at                 timestamptz,
  decision_reason            text,
  idempotency_key            text not null unique,
  decision_key               text unique,
  check (proposed_status <> effective_status_snapshot),
  check (status = 'PENDING' or (decided_by is not null and decided_at is not null)),
  check (decided_by is null or decided_by <> requested_by)       -- requester can never decide, enforced in the table too
);
create unique index attendance_amendment_one_pending on attendance_amendment_requests (attendance_record_id) where status = 'PENDING';

create or replace function guard_amendment_request() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then raise exception 'IMMUTABLE_RECORD'; end if;
  if old.status <> 'PENDING' then raise exception 'IMMUTABLE_RECORD' using detail = 'decided requests are never reopened or edited'; end if;
  if new.attendance_record_id <> old.attendance_record_id or new.proposed_status <> old.proposed_status or new.reason <> old.reason
     or new.requested_by <> old.requested_by or new.source_status_snapshot <> old.source_status_snapshot then
    raise exception 'IMMUTABLE_RECORD';
  end if;
  return new;
end $$;
create trigger attendance_amendment_requests_guard before update or delete on attendance_amendment_requests for each row execute function guard_amendment_request();

