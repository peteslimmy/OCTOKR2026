-- Single canonical effective-status projection used by every screen, report and export.
create or replace function attendance_effective_status(p_record uuid) returns text
language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(
    (select r.proposed_status from attendance_amendment_requests r where r.attendance_record_id = p_record and r.status = 'APPROVED'
      order by r.decided_at desc, r.id desc limit 1),
    (select status from attendance_records where id = p_record));
$$;

