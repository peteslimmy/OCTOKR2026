-- ---------------------------------------------------------------- grant helper (extends read-side whitelist)
create or replace function lock_down_function_grants() returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare r record;
begin
  for r in select p.oid::regprocedure as sig, p.proname from pg_proc p
           join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.prokind = 'f' and p.proname <> 'lock_down_function_grants' loop
    execute format('revoke all on function %s from public, anon, authenticated', r.sig);
    execute format('grant execute on function %s to service_role', r.sig);
    if r.proname in ('auth_has_permission','auth_bu','app_now','report_phase','quarter_is_locked','auth_can_view_bu',
                     'goal_is_done','report_goal_counts','calc_base_score','calc_final_score','active_penalty_rate',
                     'auth_has_any','attendance_effective_status','fund_balance','fund_committed')
       or r.proname like 'read\_%' then
      execute format('grant execute on function %s to authenticated', r.sig);
    end if;
  end loop;
end $$;

create or replace function auth_has_any(p_codes text[]) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (select 1 from unnest(p_codes) c where actor_has_permission(auth.uid(), c));
$$;

-- ---------------------------------------------------------------- per-user designations ("designated HR approver")
create table user_permission_grants (
  user_id       uuid not null references users(id) on delete cascade,
  permission_id uuid not null references permissions(id) on delete restrict,
  granted_by    uuid not null references users(id),
  created_at    timestamptz not null default app_now(),
  primary key (user_id, permission_id)
);

create or replace function actor_has_permission(p_actor uuid, p_code text) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (select 1 from users u where u.id = p_actor and u.status = 'ACTIVE') and (
    exists (select 1 from user_roles ur join role_permissions rp on rp.role_id = ur.role_id join permissions p on p.id = rp.permission_id
            where ur.user_id = p_actor and p.code = p_code)
    or exists (select 1 from user_permission_grants g join permissions p on p.id = g.permission_id where g.user_id = p_actor and p.code = p_code));
$$;

create or replace function users_with_permission(p_code text) returns uuid[]
language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(array_agg(distinct u.id), '{}') from users u
  where u.status = 'ACTIVE' and actor_has_permission(u.id, p_code);
$$;

create or replace function set_user_permission(p_actor uuid, p_user uuid, p_permission text, p_grant boolean) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_pid uuid;
begin
  perform require_permission(p_actor, 'roles.manage');
  if p_permission not in ('attendance.amendment.approve','attendance.amendment.request','attendance.session.manage',
                          'reporting.period.holiday.manage','weekly_report.review') then
    raise exception 'VALIDATION_ERROR' using detail = 'this permission cannot be designated individually';
  end if;
  select id into v_pid from permissions where code = p_permission;
  if not exists (select 1 from users where id = p_user) then raise exception 'NOT_FOUND'; end if;
  if p_grant then
    insert into user_permission_grants (user_id, permission_id, granted_by) values (p_user, v_pid, p_actor) on conflict do nothing;
  else
    delete from user_permission_grants where user_id = p_user and permission_id = v_pid;
  end if;
  perform write_audit(p_actor, case when p_grant then 'PERMISSION_DESIGNATED' else 'PERMISSION_DESIGNATION_REMOVED' end, 'user', p_user::text,
                      null, jsonb_build_object('permission', p_permission));
end $$;

